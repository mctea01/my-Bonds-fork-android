/**
 * The mobile citizen certificate SP account built into this build, from the environment or Gradle properties
 * (DIW_MOICA_SP_SERVICE_ID, DIW_MOICA_SP_AES_KEY, DIW_MOICA_SP_ENV = UAT or PRODUCTION; CI can pass them as secrets, see docs/release.md).
 * The generated source stays in the build directory and is never committed; without the values the app has no
 * built-in account and only the developer setting can supply one.
 */
abstract class GenerateBuiltInSp : DefaultTask() {
    @get:Input @get:Optional abstract val serviceId: Property<String>
    @get:Input @get:Optional abstract val aesKey: Property<String>
    @get:Input @get:Optional abstract val environment: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val id = serviceId.orNull?.trim()?.takeIf { it.isNotEmpty() }
        val key = aesKey.orNull?.trim()?.takeIf { it.isNotEmpty() }
        val env = environment.orNull?.trim()?.uppercase()?.takeIf { it.isNotEmpty() } ?: "UAT"
        if ((id == null) != (key == null)) throw GradleException("DIW_MOICA_SP_SERVICE_ID and DIW_MOICA_SP_AES_KEY must be set together")
        if (id != null && !Regex("[A-Za-z0-9_.-]{1,64}").matches(id)) throw GradleException("DIW_MOICA_SP_SERVICE_ID has unexpected characters")
        if (key != null && !Regex("[A-Za-z0-9+/=_-]{16,128}").matches(key)) throw GradleException("DIW_MOICA_SP_AES_KEY is not base64")
        if (env !in setOf("UAT", "PRODUCTION")) throw GradleException("DIW_MOICA_SP_ENV must be UAT or PRODUCTION")
        fun lit(v: String?) = if (v == null) "null" else "\"" + v + "\""
        val dir = outputDir.get().asFile.resolve("diw/wallet/app").apply { mkdirs() }
        dir.resolve("BuiltInSp.kt").writeText(
            """
            |package diw.wallet.app
            |
            |/** Generated by the build from DIW_MOICA_SP_*; not committed. */
            |internal object BuiltInSp {
            |    const val ENVIRONMENT: String = "$env"
            |    val serviceId: String? = ${lit(id)}
            |    val aesKeyBase64: String? = ${lit(key)}
            |}
            |""".trimMargin()
        )
    }
}

val generateBuiltInSp by tasks.registering(GenerateBuiltInSp::class) {
    fun setting(name: String) = providers.environmentVariable(name).orElse(providers.gradleProperty(name))
    serviceId.set(setting("DIW_MOICA_SP_SERVICE_ID"))
    aesKey.set(setting("DIW_MOICA_SP_AES_KEY"))
    environment.set(setting("DIW_MOICA_SP_ENV"))
    outputDir.set(layout.buildDirectory.dir("generated/builtInSp/kotlin"))
}

/** Version and commit shown on the About page; CI passes the version and GitHub sets GITHUB_SHA. */
abstract class GenerateAppBuild : DefaultTask() {
    @get:Input @get:Optional abstract val version: Property<String>
    @get:Input @get:Optional abstract val commit: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val v = version.orNull?.trim()?.takeIf { Regex("[A-Za-z0-9._+-]{1,40}").matches(it) }
        val c = commit.orNull?.trim()?.takeIf { Regex("[0-9a-fA-F]{7,40}").matches(it) }?.take(7)?.lowercase()
        fun lit(x: String?) = if (x == null) "null" else "\"" + x + "\""
        val dir = outputDir.get().asFile.resolve("diw/wallet/app").apply { mkdirs() }
        dir.resolve("AppBuild.kt").writeText(
            """
            |package diw.wallet.app
            |
            |/** Generated by the build; not committed. */
            |internal object AppBuild {
            |    val version: String? = ${lit(v)}
            |    val commit: String? = ${lit(c)}
            |}
            |""".trimMargin()
        )
    }
}

val generateAppBuild by tasks.registering(GenerateAppBuild::class) {
    version.set(providers.gradleProperty("diw.versionName").orElse(providers.gradleProperty("diw.desktopVersion")))
    commit.set(providers.environmentVariable("GITHUB_SHA"))
    outputDir.set(layout.buildDirectory.dir("generated/appBuild/kotlin"))
}

