package diw.testservers.zkpdf

import diw.wallet.core.document.Check
import diw.wallet.core.document.DocumentInspector
import diw.wallet.core.document.DocumentTrustSource
import diw.wallet.core.document.LaterChanges
import diw.wallet.core.document.pdf.*
import diw.wallet.core.document.zkpdf.PdfZkSupport
import diw.wallet.core.env.EnvironmentPolicy
import diw.wallet.core.env.TrustEnvironment
import diw.wallet.core.trust.*
import kotlinx.coroutines.runBlocking
import org.apache.pdfbox.Loader
import org.apache.pdfbox.rendering.PDFRenderer
import org.multipaz.crypto.X509Cert
import org.multipaz.storage.ephemeral.EphemeralStorage
import java.io.File
import java.util.Base64
import kotlin.test.*
import kotlin.time.Instant

class SyntheticDocumentsTest {
    companion object {
        private val root = generateSequence(File(".").canonicalFile) { it.parentFile }.first { File(it, "settings.gradle.kts").isFile }
        private val fonts = SyntheticDocuments.Fonts(File(root, "tools/zkpdf-testdocs/fonts"))
        private val material by lazy { runBlocking { SyntheticDocuments.material() } }
        private val generated by lazy { runBlocking { SyntheticDocuments.generate(fonts, material) } }
        private val destination = File(root, "test-servers/src/test/resources/zkpdf")
    }

    @Test fun committedArtifactsMatchDeterministicGenerator() = runBlocking<Unit> {
        val second = SyntheticDocuments.generate(fonts, SyntheticDocuments.material())
        assertEquals(generated.keys, second.keys)
        for ((name, bytes) in generated) {
            assertTrue(bytes.contentEquals(second.getValue(name)), "Fixture is not reproducible: $name")
            if (System.getenv("DIW_ZKPDF_WRITE_FIXTURES") == "1") {
                destination.mkdirs()
                File(destination, name).writeBytes(bytes)
            }
            val committed = File(destination, name)
            assertTrue(committed.isFile, "Regenerate missing fixture: $name")
            assertTrue(bytes.contentEquals(committed.readBytes()), "Committed fixture differs: $name")
        }
    }

    private suspend fun trust(): DocumentTrustSource {
        val registry = TrustRegistry(EphemeralStorage(), EnvironmentPolicy(testEnvironmentEnabled = true))
        registry.addAnchor(TrustRole.DOCUMENT, TrustEnvironment.TEST, material.pki.iacaCert, "DIW Synthetic Test Root", official = false, source = "synthetic-fixture")
        return object : DocumentTrustSource {
            override suspend fun decide(role: TrustRole, chain: List<X509Cert>, at: Instant): TrustDecision = registry.decide(role, chain, at)
            override suspend fun fetchIssuerCertificates(url: String) = emptyList<ByteArray>()
        }
    }

    @Test fun everyPdfHasAnIntactSignatureFromTheTestPki() = runBlocking<Unit> {
        val trust = trust()
        for ((name, bytes) in generated.filterKeys { it.endsWith(".pdf") }) {
            val report = DocumentInspector.inspect(bytes, name, trust)
            assertEquals(1, report.signatures.size, "Signature count: $name")
            val signature = report.signatures.single()
            assertEquals(Check.PASS, signature.integrity, "Signature integrity: $name")
            val certificate = assertNotNull(signature.signer)
            assertTrue(Base64.getDecoder().decode(certificate.der).contentEquals(material.signer.certificateChain.first()), "Unexpected signing certificate")
            assertEquals(if (name == "student-modified.pdf") LaterChanges.OTHER else LaterChanges.NONE, signature.laterChanges, "Revision classification: $name")
        }
    }

    @Test fun wordLikeTextAndDigitDecodersMatchTheFictionalData() {
        for ((name, expected) in listOf("student.pdf" to SyntheticDocuments.studentText, "travel-rc4.pdf" to SyntheticDocuments.travelText)) {
            val pdf = PdfFile(generated.getValue(name))
            val runs = PdfTextExtractor.runs(pdf, 0)
            assertTrue(runs.map { it.text } == expected, "Decoded fixture text mismatch")
            assertTrue(PdfTextExtractor.layoutRuns(runs) == PdfTextExtractor.extract(pdf), "P3 and WP2 text disagree")
            val decoders = PdfZkSupport.fontDecoders(pdf, 0)
            val cid = assertNotNull(decoders["FHanzi"])
            assertEquals(2, cid.kind)
            assertTrue(cid.digitCodes()!!.contentEquals(IntArray(10) { fonts.cid.getValue(it.toString()) }))
            if (name == "student.pdf") {
                assertTrue(runs.any { it.font == "FLatin" && it.literal })
                assertEquals(1, decoders.getValue("FLatin").kind)
            } else assertTrue(runs.all { it.font == "FHanzi" })
            assertEquals(4, PdfZkSupport.pageContentObject(pdf, 0))
        }
    }

    @Test fun rc4WithEmptyPasswordPreservesSignedStreamAndDecodesWithThePublicKeyStream() {
        val bytes = generated.getValue("travel-rc4.pdf")
        val pdf = PdfFile(bytes, "")
        assertTrue(pdf.encrypted)
        val objectNumber = PdfZkSupport.pageContentObject(pdf, 0)
        val extent = PdfZkSupport.streamExtent(pdf, objectNumber)
        val encrypted = bytes.sliceArray(extent)
        val keyStream = assertNotNull(PdfZkSupport.rc4KeyStream(pdf, objectNumber, encrypted.size))
        val plain = ByteArray(encrypted.size) { (encrypted[it].toInt() xor keyStream[it].toInt()).toByte() }
        val stream = pdf.getObject(objectNumber) as PdfStream
        assertTrue(plain.contentEquals(stream.data), "RC4 stream differs")
        assertTrue(pdf.decode(stream).size <= SyntheticDocuments.MAX_PLAIN)
        Loader.loadPDF(bytes, "").use { assertTrue(it.isEncrypted); assertEquals(1, it.numberOfPages) }
    }

    @Test fun adversarialFixturesContainTheRequiredStructuralChanges() {
        fun content(name: String): ByteArray {
            val pdf = PdfFile(generated.getValue(name))
            return pdf.decode(pdf.getObject(PdfZkSupport.pageContentObject(pdf, 0)) as PdfStream)
        }
        assertTrue(" BI " in content("student-inline-image.pdf").decodeToString())
        assertTrue("/ActualText" in content("student-actual-text.pdf").decodeToString())
        assertTrue(content("student-oversized.pdf").size > SyntheticDocuments.MAX_PLAIN)
        val original = generated.getValue("student.pdf")
        val changed = generated.getValue("student-modified.pdf")
        assertTrue(changed.copyOf(original.size).contentEquals(original), "Incremental revision rewrote signed bytes")
        assertTrue(!content("student.pdf").contentEquals(content("student-modified.pdf")))
    }

    @Test fun embeddedFontsAndQrProduceRenderablePages() {
        for (name in listOf("student.pdf", "travel-rc4.pdf")) {
            Loader.loadPDF(generated.getValue(name), "").use { pdf ->
                val image = PDFRenderer(pdf).renderImageWithDPI(0, 72f)
                var ink = 0
                for (y in 0 until image.height) for (x in 0 until image.width) if ((image.getRGB(x, y) and 0xffffff) != 0xffffff) ink++
                assertTrue(ink > 1000, "Synthetic page did not render")
                assertTrue(pdf.getPage(0).resources.getFont(org.apache.pdfbox.cos.COSName.getPDFName("FHanzi")).isEmbedded)
            }
        }
    }
}
