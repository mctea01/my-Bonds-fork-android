#!/usr/bin/env python3
"""Writes core/.../c2pa/SoftBindingAlgorithms.kt from the C2PA soft binding algorithm list.

  python3 -I tools/c2pa/update_softbinding.py [LIST.json] [--commit SHA]

Without LIST.json the list is downloaded from the default branch of github.com/c2pa-org/softbinding-algorithm-list
(CC-BY-4.0, attributed in NOTICE). Only the identifier, algorithm name, type, media types and description are kept.
"""
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "core/src/commonMain/kotlin/diw/wallet/core/document/c2pa/SoftBindingAlgorithms.kt"
URL = "https://raw.githubusercontent.com/c2pa-org/softbinding-algorithm-list/main/softbinding-algorithm-list.json"


def kotlin_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("$", "\\$") + '"'


def main(argv):
    commit = None
    if "--commit" in argv:
        i = argv.index("--commit")
        commit = argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    if argv:
        data = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            data = json.loads(r.read().decode("utf-8"))
    rows = []
    for e in sorted(data, key=lambda x: x["identifier"]):
        meta = e.get("entryMetadata") or {}
        media = ",".join(e.get("decodedMediaTypes") or [])
        rows.append("        SoftBindingAlgorithm(%d, %s, %s, %s, %s)," % (
            e["identifier"], kotlin_string(e["alg"]), kotlin_string(e["type"]), kotlin_string(media),
            kotlin_string(meta.get("description", ""))))
    source = "c2pa-org/softbinding-algorithm-list" + (" at " + commit if commit else "")
    lines = [
        "package diw.wallet.core.document.c2pa",
        "",
        "/** One entry of the C2PA soft binding algorithm list: a registered watermark or fingerprint algorithm. */",
        "data class SoftBindingAlgorithm(val identifier: Int, val alg: String, val type: String, val mediaTypes: String, val description: String)",
        "",
        "/**",
        " * The C2PA soft binding algorithm list (%s, CC-BY-4.0), generated by" % source,
        " * tools/c2pa/update_softbinding.py; do not edit by hand. Names a c2pa.soft-binding algorithm when a manifest uses one.",
        " */",
        "object SoftBindingAlgorithms {",
        "    val ALL: List<SoftBindingAlgorithm> = listOf(",
    ] + rows + [
        "    )",
        "",
        "    private val byAlg = ALL.associateBy { it.alg }",
        "",
        "    fun find(alg: String): SoftBindingAlgorithm? = byAlg[alg]",
        "}",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %d algorithms to %s" % (len(rows), OUT.relative_to(ROOT)))


if __name__ == "__main__":
    main(sys.argv[1:])
