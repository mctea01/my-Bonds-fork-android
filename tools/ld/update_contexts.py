#!/usr/bin/env python3
"""Regenerates core/.../w3c/ld/LdContexts.kt: the JSON-LD contexts the wallet resolves without the network.

Usage: python3 tools/ld/update_contexts.py [--offline DIR]
With --offline the files are read from DIR (named like the keys below plus .jsonld) instead of fetched.
Review the diff: a changed context changes what signed credentials mean.
"""
import json
import sys
import urllib.request
from pathlib import Path

CONTEXTS = {
    "credentials-v1": "https://www.w3.org/2018/credentials/v1",
    "credentials-v2": "https://www.w3.org/ns/credentials/v2",
    "credentials-examples-v1": "https://www.w3.org/2018/credentials/examples/v1",
    "credentials-examples-v2": "https://www.w3.org/ns/credentials/examples/v2",
    "data-integrity-v1": "https://w3id.org/security/data-integrity/v1",
    "data-integrity-v2": "https://w3id.org/security/data-integrity/v2",
    "multikey-v1": "https://w3id.org/security/multikey/v1",
    "ed25519-2020-v1": "https://w3id.org/security/suites/ed25519-2020/v1",
    "jws-2020-v1": "https://w3id.org/security/suites/jws-2020/v1",
    "secp256k1-2019-v1": "https://w3id.org/security/suites/secp256k1-2019/v1",
    "security-v1": "https://w3id.org/security/v1",
    "security-v2": "https://w3id.org/security/v2",
    "bbs-v1": "https://w3id.org/security/bbs/v1",
    "did-v1": "https://www.w3.org/ns/did/v1",
    "status-list-2021": "https://w3id.org/vc/status-list/2021/v1",
    "render-method-v1": "https://w3id.org/vc/render-method/v1",
    "citizenship-v4rc1": "https://w3id.org/citizenship/v4rc1",
    "vdl-v1": "https://w3id.org/vdl/v1",
    "vdl-aamva-v1": "https://w3id.org/vdl/aamva/v1",
}
# Context URLs that serve the same document as another entry.
ALIASES = {
    "https://www.w3.org/ns/did/v1": ["https://w3id.org/did/v1"],
    "https://w3id.org/security/v2": ["https://w3id.org/security/v2/"],
}

OUT = Path(__file__).resolve().parents[2] / "core/src/commonMain/kotlin/diw/wallet/core/w3c/ld/LdContexts.kt"


def load(name, url, offline):
    if offline:
        return (Path(offline) / f"{name}.jsonld").read_text(encoding="utf-8")
    req = urllib.request.Request(url, headers={"Accept": "application/ld+json, application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def main():
    offline = sys.argv[2] if len(sys.argv) > 2 and sys.argv[1] == "--offline" else None
    entries = []
    for name, url in CONTEXTS.items():
        text = load(name, url, offline)
        compact = json.dumps(json.loads(text), ensure_ascii=False, separators=(",", ":"))
        literal = compact.replace("$", "${'$'}")
        assert '"""' not in literal
        for u in [url] + ALIASES.get(url, []):
            entries.append((u, name))
        entries.append((None, (name, literal)))
    lines = [
        "package diw.wallet.core.w3c.ld",
        "",
        "// Generated by tools/ld/update_contexts.py. Do not edit by hand.",
        "",
        "/** JSON-LD context documents bundled with the wallet, keyed by context URL. */",
        "internal object LdContexts {",
    ]
    for _, value in [e for e in entries if e[0] is None]:
        name, literal = value
        ident = name.upper().replace("-", "_")
        lines.append(f'    private const val {ident} = """{literal}"""')
    lines.append("")
    lines.append("    val BUILT_IN: Map<String, String> = mapOf(")
    for url, name in [e for e in entries if e[0] is not None]:
        lines.append(f'        "{url}" to {name.upper().replace("-", "_")},')
    lines.append("    )")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
